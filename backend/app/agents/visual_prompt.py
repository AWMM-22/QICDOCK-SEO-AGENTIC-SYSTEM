logger = logging.getLogger(__name__)


from pydantic import BaseModel, Field, model_validator


class VisualPromptOutput(BaseModel):
    visual_concept: str = Field(description="High-level visual concept description")
    image_prompt: str = Field(description="Detailed image generation prompt for AI image provider (cover/hero image)")
    image_prompts: List[str] = Field(default_factory=list, description="Array of image prompts, one per slide/frame")
    carousel_design: List[Dict[str, Any]] = Field(default_factory=list, description="Slide-by-slide design for carousels")
    visual_requirements: List[str] = Field(default_factory=list, description="Critical visual requirements to preserve")
    aspect_ratio_recommendation: str = Field(default="1:1", description="Recommended aspect ratio")

    @model_validator(mode="before")
    @classmethod
    def _normalize_keys(cls, data: Any) -> Any:
        if isinstance(data, dict):
            new_data = {}
            for k, v in data.items():
                k_str = str(k).lower().replace(" ", "_")
                if k_str in ("visual_concept", "visualconcept", "concept"):
                    new_data["visual_concept"] = str(v) if v else ""
                elif k_str in ("image_prompt", "imageprompt", "prompt"):
                    new_data["image_prompt"] = str(v) if v else ""
                elif k_str in ("image_prompts", "imageprompts", "prompts", "slide_prompts"):
                    if isinstance(v, list):
                        new_data["image_prompts"] = [str(x) for x in v]
                    elif isinstance(v, str):
                        new_data["image_prompts"] = [v]
                    else:
                        new_data["image_prompts"] = []
                elif k_str in ("carousel_design", "carouseldesign", "carousel"):
                    new_data["carousel_design"] = v if isinstance(v, list) else []
                elif k_str in ("visual_requirements", "visualrequirements", "requirements"):
                    new_data["visual_requirements"] = [str(x) for x in v] if isinstance(v, list) else []
                elif k_str in ("aspect_ratio_recommendation", "aspect_ratio", "aspectratio"):
                    new_data["aspect_ratio_recommendation"] = str(v) if v else "1:1"
                else:
                    new_data[k_str] = v
            return new_data
        return data


