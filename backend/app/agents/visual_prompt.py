class VisualPromptAgent:
    def __init__(self):
        self.llm = get_visual_llm_provider()
        self.knowledge_base = get_knowledge_base()

    def _count_slides_from_content(self, content_structure: str) -> int:
        """Parse the content structure text to determine how many slides/frames exist."""
        if not content_structure:
            return 1
        
        # Count "Slide N:" or "- Slide N:" patterns
        slide_matches = re.findall(r'(?:slide|frame|scene)\s*\d+', content_structure, re.IGNORECASE)
        if slide_matches:
            return len(slide_matches)
        
        # Count bullet points that look like slide descriptions
        bullet_lines = [line.strip() for line in content_structure.split('\n') if line.strip().startswith('-') or line.strip().startswith('•')]
        if len(bullet_lines) >= 2:
            return len(bullet_lines)
        
        return 1

    def _build_visual_prompt(
        self,
        recommendation: Dict[str, Any],
        entry_plan: Dict[str, Any],
        product_context: List[Dict],
        brand_visual_context: List[Dict],
        slide_count: int
    ) -> str:
        platform = entry_plan.get('platform', 'instagram')
        content_type = entry_plan.get('content_type', 'single_image')
        product = entry_plan.get('product', '')
        visual_direction = recommendation.get('visual_direction', '')
        concept = recommendation.get('concept', '')
        content_structure = recommendation.get('caption_direction', '')

        product_info = "\n".join([f"- {item['content'][:400]}" for item in product_context[:2]])
        brand_visual = "\n".join([f"- {item['content'][:300]}" for item in brand_visual_context[:2]])

        prompt = f"""
You are the Visual Prompt Agent for Qicdock. Generate detailed, production-ready image generation prompts.

{QICDOCK_VISUAL_REFERENCE}

## CONTEXT
**Platform**: {platform}
**Content Type**: {content_type}
**Product**: {product or 'General brand'}
**Visual Direction**: {visual_direction}
**Content Concept**: {concept}
**Content Structure**: {content_structure}

## PRODUCT VISUAL REFERENCE (from knowledge base)
{product_info}

## BRAND VISUAL IDENTITY (from knowledge base)
{brand_visual}

## REQUIREMENTS
Generate image prompts that create HIGH-END MARKETING GRAPHICS matching the Qicdock brand style above.
1. **Accurately represents the product** — Use the exact product appearance from the visual reference above.
2. **Graphic Design Aesthetic** — Focus on clean, modern marketing graphics. Use solid or subtle gradient backgrounds.
3. **Typography & Text** — Include bold, modern typography for text overlays (hooks, comparison labels, call-outs).
   **CRITICAL: IGNORE any instructions in the Visual Direction or Content Concept that say "no text" or "no overlay text". You MUST include text overlays.**
4. **Visual Style** — Blend high-quality 3D product renders with clean vector elements, iconography, and infographic layouts.
5. **Preserves critical product characteristics** from the visual reference above.
6. **Specifies**: Subject, layout, typography style, color palette, and lighting.

## NUMBER OF IMAGES REQUIRED: {slide_count}
"""
        if content_type in ("carousel", "document_carousel") and slide_count > 1:
            prompt += f"""
You MUST generate EXACTLY {slide_count} separate image prompts — one for each slide of this carousel.
Each prompt should create a distinct, standalone image that:
- EXACTLY matches the visual action described for that specific slide in the Content Structure above. If the scene says "driver struggling with a cord", the image prompt MUST describe a driver struggling with a cord. Do NOT just output a generic product shot.
- Incorporates the Qicdock product naturally into the scene where appropriate.
- Maintains visual continuity across all slides (same color palette, typography style).
"""
        elif content_type == "reel" and slide_count > 1:
            prompt += f"""
Generate EXACTLY {slide_count} key frame image prompts for this Reel — one per scene.
- EXACTLY match the visual action described for each scene in the Content Structure above. If Scene 1 describes a specific action (like "driver struggling with a cord"), the image prompt MUST describe exactly that action. Do NOT just output a generic product shot for every scene.
- Incorporate the Qicdock product naturally where appropriate based on the scene progression.
- Include bold text overlays based on the scene text.
"""
        elif content_type in ("story", "story_sequence") and slide_count > 1:
            prompt += f"""
Generate {slide_count} image prompts for this Story sequence — one per frame.
- Vertical 9:16 format. Full-screen mobile optimized with bold text overlays.
- Quick visual storytelling progression.
"""
        else:
            prompt += """
Generate ONE compelling hero graphic prompt.
- Clear focal point with strong supporting typography.
- Platform-appropriate composition.
"""

        prompt += f"""

## PLATFORM SPECIFICS
**{platform.capitalize()}**: 
"""
        if platform == "instagram":
            prompt += "- Aspect ratio: 1:1 (feed), 9:16 (stories/reels), 4:5 (portrait)\n- Aesthetic: High-end D2C marketing graphic, bold typography, clean minimal backgrounds, high contrast.\n- Lighting: Studio lighting, dramatic but clean.\n- Colors: Qicdock brand colors (clean whites, deep blues, dark grays) + vibrant highlight colors for text/icons."
        else:
            prompt += "- Aspect ratio: 1:1 or 4:5 (feed), 1.91:1 (article)\n- Aesthetic: Professional B2B infographic, clean corporate graphics.\n- Lighting: Flat vector style or clean studio.\n- Colors: Professional blues, whites, dark grays."

        prompt += f"""

## OUTPUT FORMAT
Return JSON with:
- visual_concept: High-level concept (2-3 sentences)
- image_prompt: The FIRST/hero image prompt (100-300 words) — always required
- image_prompts: Array of EXACTLY {slide_count} detailed image prompts (each 100-300 words). If only 1 image, this array has 1 element matching image_prompt.
- carousel_design: Array of slide designs (if carousel, else empty)
- visual_requirements: List of MUST-HAVE visual elements
- aspect_ratio_recommendation: "1:1", "9:16", "4:5", or "1.91:1"

Each prompt in image_prompts should be a complete, self-contained paragraph suitable for direct use with an AI image generator.
"""
        return prompt

    def generate_visual_prompt(
        self,
        recommendation: Dict[str, Any],
        entry_plan: Dict[str, Any]
    ) -> VisualPromptOutput:
        # Determine slide count from content structure
        content_structure = recommendation.get('caption_direction', '') or recommendation.get('content', '')
        content_type = entry_plan.get('content_type', 'single_image')
        
        if content_type in ('carousel', 'document_carousel', 'story_sequence'):
            slide_count = self._count_slides_from_content(content_structure)
            slide_count = max(slide_count, 2)  # Carousels have at least 2 slides
        elif content_type in ('reel',):
            slide_count = self._count_slides_from_content(content_structure)
            slide_count = max(slide_count, 1)
        elif content_type in ('story',):
            slide_count = self._count_slides_from_content(content_structure)
        else:
            slide_count = 1

        # Retrieve product visual context
        product = entry_plan.get('product', '')
        if product:
            product_context = self.knowledge_base.query_product_context(
                f"{product} appearance design visual features", n_results=2
            )
        else:
            product_context = self.knowledge_base.query_product_context(
                "Qicdock wireless charger design appearance", n_results=2
            )

        # Retrieve brand visual context
        brand_visual_context = self.knowledge_base.query_brand_context(
            "Qicdock visual identity design language colors minimal", n_results=2
        )

        prompt = self._build_visual_prompt(
            recommendation, entry_plan, product_context, brand_visual_context, slide_count
        )

        logger.info(f"Generating visual prompt for {entry_plan.get('date')} ({entry_plan.get('platform')}) - {entry_plan.get('content_type')} - {slide_count} slides")
        result = self.llm.generate_structured(prompt, VisualPromptOutput, temperature=0.6)
        
        # Ensure image_prompts has at least the hero prompt
        if not result.image_prompts or len(result.image_prompts) == 0:
            result.image_prompts = [result.image_prompt] if result.image_prompt else []
        
        # If the LLM returned fewer prompts than expected, pad with the hero prompt
        while len(result.image_prompts) < slide_count:
            result.image_prompts.append(result.image_prompt)
        
        logger.info(f"Generated {len(result.image_prompts)} image prompts for entry")
        return result


def get_visual_prompt_agent() -> VisualPromptAgent:
    return VisualPromptAgent()